-- ????????????????????????????????????????????????????????????????????????????
--  TRIGGERS (Gatilhos de Validação e Automação no Banco)
-- ????????????????????????????????????????????????????????????????????????????

DELIMITER //

-- 1. trg_valida_estoque: Dispara ANTES de inserir uma venda.
-- Bloqueia a transação e devolve um erro para o Node.js se não houver salgadinho suficiente.
DROP TRIGGER IF EXISTS trg_valida_estoque //
CREATE TRIGGER trg_valida_estoque
BEFORE INSERT ON vendas
FOR EACH ROW
BEGIN
    DECLARE v_estoque_atual INT;

    -- Descobre o estoque do produto que está sendo vendido
    SELECT estoque INTO v_estoque_atual 
    FROM produtos 
    WHERE id_produto = NEW.id_produto;

    -- Se tentar vender mais do que tem, explode o erro e cancela a venda na hora!
    IF v_estoque_atual < NEW.quantidade THEN
        SIGNAL SQLSTATE '45000' 
        SET MESSAGE_TEXT = 'Operação cancelada: Estoque insuficiente para realizar esta venda.';
    END IF;
END //


-- 2. trg_atualiza_estoque: Dispara DEPOIS que a venda é inserida com sucesso.
-- Vai lá na tabela de produtos e subtrai a quantidade comprada do estoque.
DROP TRIGGER IF EXISTS trg_atualiza_estoque //
CREATE TRIGGER trg_atualiza_estoque
AFTER INSERT ON vendas
FOR EACH ROW
BEGIN
    UPDATE produtos 
    SET estoque = estoque - NEW.quantidade 
    WHERE id_produto = NEW.id_produto;
END //

DELIMITER ;